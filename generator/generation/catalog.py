class StoreCatalog:
    """Фабрика магазинов сети по количеству точек из конфигурации."""

    def __init__(self, count: int) -> None:
        if not 1 <= count <= len(_STORE_TEMPLATES):
            raise ValueError(
                f"запрошено {count} магазинов, доступно 1..{len(_STORE_TEMPLATES)}"
            )
        self._templates = _STORE_TEMPLATES[:count]

    def stores(self, now: datetime) -> list[Store]:
        return [
            Store(
                store_id=template.store_id,
                name=template.name,
                city=template.city,
                district=template.district,
                store_format=template.store_format,
                opened_at=template.opened_at,
                updated_at=now,
            )
            for template in self._templates
        ]

    def profile_for(self, store: Store) -> StoreProfile:
        return next(
            template.profile
            for template in self._templates
            if template.store_id == store.store_id
        )


class ProductCatalog:
    """Фабрика товаров: цены и себестоимость фиксируются случайно по категории."""

    def __init__(self, count: int, rng: random.Random) -> None:
        self._rng = rng
        self._items = self._build(count)

    def _build(self, count: int) -> list[tuple[str, str, str, str, float, float]]:
        pools: list[tuple[str, list[tuple[str, str, str, float, float]]]] = [
            (category, list(items)) for category, items in _PRODUCT_TEMPLATES.items()
        ]
        total = sum(len(items) for _category, items in pools)
        flat: list[tuple[str, str, str, str, float, float]] = []

        if count <= total:
            # Интерливинг по категориям: в каталоге любого размера представлены
            # все категории, а не «первые N товаров первого блока».
            while len(flat) < count and any(items for _c, items in pools):
                for _category, items in pools:
                    if items and len(flat) < count:
                        name, subcategory, unit, low, high = items.pop(0)
                        flat.append(
                            (name, _category, subcategory, unit, low, high)
                        )
            return flat

        for category, items in pools:
            for name, subcategory, unit, low, high in items:
                flat.append((name, category, subcategory, unit, low, high))

        base = list(flat)
        while len(flat) < count:
            name, category, subcategory, unit, low, high = base[len(flat) % len(base)]
            pack = 2 + len(flat) // len(base)
            flat.append(
                (f"{name}, упаковка {pack} шт", category, subcategory, unit,
                 low * pack * 0.95, high * pack * 0.95)
            )
        return flat

    def products(self, now: datetime) -> list[Product]:
        rng = self._rng
        products: list[Product] = []
        for index, (name, category, subcategory, unit, low, high) in enumerate(
            self._items, start=1
        ):
            price = money(rng.uniform(low, high))
            markup = 1.18 + 0.14 * rng.random()
            products.append(
                Product(
                    product_id=index,
                    sku=f"SKU-{category[:2].upper()}-{index:04d}",
                    name=name,
                    category=category,
                    subcategory=subcategory,
                    supplier=rng.choice(SUPPLIERS),
                    unit=unit,
                    price=price,
                    cost=money(float(price) / markup),
                    is_organic=rng.random() < 0.14,
                    is_available=True,
                    updated_at=now,
                )
            )
        return products

    @staticmethod
    def category_weights() -> dict[str, float]:
        return dict(CATEGORY_WEIGHTS)
